export function requireCurrentAsset(asset) {
  if (!asset.assetEntry?.exists || asset.assetEntry.dataBytes < 287 || asset.assetEntry.version !== 1) throw new Error("LEGACY_OR_TRUNCATED_ASSET_ENTRY: current TcapAssetEntryV1 is required");
  if (!asset.governancePolicy?.exists || !asset.extensionPolicy?.exists) throw new Error("MISSING_V2_POLICY_ACCOUNTS: run network:init-asset with TCAP governance");
}
export function envValue(name, fallback = "") {
  const text = fs.existsSync(DEFAULTS) ? fs.readFileSync(DEFAULTS, "utf8") : "";
  return text.match(new RegExp(`^${name}=(.*)$`, "m"))?.[1] ?? fallback;
}
export function writeDefaults(values) {
  const lines = ["# Live, non-secret Devnet TCAP credit defaults. Generated by network:set-defaults.", ...Object.entries(values).map(([key, value]) => `${key}=${value}`), ""];
  const dir = path.dirname(DEFAULTS); fs.mkdirSync(dir, { recursive: true });
  const temp = `${DEFAULTS}.${process.pid}.tmp`; fs.writeFileSync(temp, lines.join("\n"), { encoding: "utf8", mode: 0o600 }); fs.renameSync(temp, DEFAULTS);
}
