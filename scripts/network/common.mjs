export function keypairPath(options = {}) {
  const explicit = options["governance-keypair"] ?? process.env.TCAP_GOVERNANCE_KEYPAIR;
  const wallet = process.env.TCAP_GOVERNANCE_WALLET;
  if (!explicit && wallet) {
    try {
      new PublicKey(wallet);
      throw new Error("TCAP_GOVERNANCE_WALLET_ADDRESS_ONLY: public address cannot sign; also set TCAP_GOVERNANCE_KEYPAIR to the matching secret keypair");
    } catch (error) {
      if (String(error?.message).startsWith("TCAP_GOVERNANCE_WALLET_ADDRESS_ONLY:")) throw error;
    }
  }
  const selected = explicit
    ?? process.env.TCAP_GOVERNANCE_WALLET
    ?? process.env.SOLANA_WALLET
    ?? path.join(os.homedir(), ".config/solana/id.json");
  return selected.startsWith("~/") ? path.join(os.homedir(), selected.slice(2)) : selected;
}
export function loadKeypair(file) {
  if (!fs.existsSync(file)) throw new Error(`MISSING_GOVERNANCE_KEYPAIR: ${file} does not exist; set TCAP_GOVERNANCE_KEYPAIR or pass --governance-keypair`);
  try {
    const signer = Keypair.fromSecretKey(Uint8Array.from(JSON.parse(fs.readFileSync(file, "utf8"))));
    if (process.env.TCAP_GOVERNANCE_WALLET) {
      try {
        const expected = new PublicKey(process.env.TCAP_GOVERNANCE_WALLET);
        if (!expected.equals(signer.publicKey)) throw new Error(`TCAP_GOVERNANCE_WALLET_MISMATCH: address ${expected.toBase58()} does not match supplied keypair ${signer.publicKey.toBase58()}`);
      } catch (error) {
        if (String(error?.message).startsWith("TCAP_GOVERNANCE_WALLET_MISMATCH:")) throw error;
      }
    }
    return signer;
  }
  catch (error) {
    if (String(error?.message).startsWith("TCAP_GOVERNANCE_WALLET_MISMATCH:")) throw error;
    throw new Error("INVALID_GOVERNANCE_KEYPAIR: expected a Solana 64-byte JSON keypair; private bytes are never logged");
  }
}
