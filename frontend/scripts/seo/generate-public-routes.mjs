import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { defaultPublicRouteSettings, publicRouteOverrides } from "./public-route-settings.mjs";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const frontendDirectory = path.resolve(scriptDirectory, "../..");
const publicPagesDirectory = path.join(frontendDirectory, "app", "(public)");
const outputPath = path.join(frontendDirectory, "src", "seo", "generated-public-routes.ts");
const pageFilePattern = /^page\.(?:js|jsx|ts|tsx)$/;

async function discoverPageFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await discoverPageFiles(entryPath)));
    else if (pageFilePattern.test(entry.name)) files.push(entryPath);
  }
  return files;
}

function pageFileToRoute(pageFile) {
  const relativeDirectory = path.relative(publicPagesDirectory, path.dirname(pageFile));
  const segments = relativeDirectory === "" ? [] : relativeDirectory.split(path.sep);
  if (segments.some((segment) => segment.startsWith("[") || segment.startsWith("@") || segment.startsWith("_"))) return null;
  const urlSegments = segments.filter((segment) => !(segment.startsWith("(") && segment.endsWith(")")));
  return urlSegments.length === 0 ? "/" : `/${urlSegments.join("/")}`;
}

function serializeRoutes(routes) {
  const serializedRoutes = routes.map((route) => `  ${JSON.stringify(route)},`).join("\n");
  return `// Generated by scripts/seo/generate-public-routes.mjs. Do not edit.
import type { PublicRoute } from "./route-types";

export const PUBLIC_ROUTES = [
${serializedRoutes}
] satisfies PublicRoute[];
`;
}

const routePaths = (await discoverPageFiles(publicPagesDirectory))
  .map(pageFileToRoute)
  .filter((routePath) => routePath !== null)
  .sort((left, right) => left === "/" ? -1 : right === "/" ? 1 : left.localeCompare(right));
const uniqueRoutePaths = [...new Set(routePaths)];
const unknownOverrides = Object.keys(publicRouteOverrides).filter((routePath) => !uniqueRoutePaths.includes(routePath));
if (unknownOverrides.length) {
  throw new Error(`SEO settings reference undiscovered public routes: ${unknownOverrides.join(", ")}`);
}

const output = serializeRoutes(uniqueRoutePaths.map((routePath) => ({
  path: routePath,
  ...defaultPublicRouteSettings,
  ...publicRouteOverrides[routePath],
})));
const existingOutput = await readFile(outputPath, "utf8").catch(() => "");
if (existingOutput !== output) {
  await writeFile(outputPath, output, "utf8");
  console.log(`Generated ${uniqueRoutePaths.length} public SEO routes.`);
} else {
  console.log(`Public SEO routes are current (${uniqueRoutePaths.length}).`);
}
